"""Generate docs/old-links.js: sends old WordPress addresses (?p=, ?page_id=, ?cat=) to the right section.

GitHub Pages cannot do server redirects, so index.html loads this script.
usage: python3 tools/make_old_links.py tools/old-wp-inventory.json docs/old-links.js
"""
import json, sys

inv = json.load(open(sys.argv[1], encoding="utf-8"))
# old page slug -> new section
PAGE_TARGETS = {
    "": ["home", "home-v2"],
    "research": ["research", "research-2", "research-nuno-crato"],
    "education": ["education", "education-2", "education-nuno-crato", "teaching"],
    "presentations": ["presentations", "presentations-2", "presentations-nuno-crato", "ultima-aula", "ultima-licao"],
    "publications": [
        "publications", "publications-2", "publications-nuno-crato", "books", "o-manual-escolar",
        "improving-a-countrys-education-pisa-results-in-10-countries",
        "einsteins-eclipse-from-lisbon-and-london-to-sobral-and-the-island-of-principe", "teste",
    ],
    "media": [
        "media", "advocacy", "events", "upcoming-events", "press-media", "pictures",
        "jornal-expresso", "jornal-de-noticias", "forbes", "jornal-diario-de-noticias", "jornal-publico",
        "lusa", "jornal-sol", "rakings-2019", "846-2",
        "ensino-a-distancia-pode-ser-positivo-mas-apenas-como-complemento",
        "a-conversa-com-eduardo-marcal-grilo", "a-educacao-numa-encruzilhadaos-resultados-do-pisa",
        "entrevista-ao-jornal-sol-flexibilizacao-curricular",
        "resposta-a-entrevista-manuel-valsassina-heitor-expresso", "entrevista-jornal-sol-2018",
        "entrevista-a-forbes-portugual-2018", "a-responsabilidade-dos-economistas-na-educacao",
        "entrevista-diario-de-noticias-2016", "2003-european-mathematical-society-first-prize",
    ],
    "about": ["about", "about-me", "about-nuno-crato", "curriculum-vitae"],
}
CAT_TARGETS = {43: "publications", 58: "research", 50: "education", 59: "media", 45: "media", 57: "media"}


slug_to_target = {slug: target for target, slugs in PAGE_TARGETS.items() for slug in slugs}
pages = {str(p["id"]): slug_to_target[p["slug"]] for p in inv["pages"] if p["slug"] in slug_to_target}
cats = {str(k): v for k, v in CAT_TARGETS.items()}
posts = {}
for p in inv["posts"]:
    c = set(p["cats"])
    posts[str(p["id"])] = "publications" if 43 in c else "research" if 58 in c else "education" if 50 in c else "media"
js = ("// Generated by tools/make_old_links.py - do not edit by hand.\n"
      "(function(){var q=new URLSearchParams(location.search);\n"
      "var m={p:%s,page_id:%s,cat:%s};\n"
      "for(var k in m){var v=q.get(k);if(v&&m[k][v]!==undefined){location.replace(m[k][v]||'./');return;}}})();\n") % (
    json.dumps(posts, separators=(",", ":")), json.dumps(pages, separators=(",", ":")), json.dumps(cats, separators=(",", ":")))
open(sys.argv[2], "w", encoding="utf-8").write(js)
print(len(posts), "posts,", len(pages), "pages,", len(cats), "categories")
